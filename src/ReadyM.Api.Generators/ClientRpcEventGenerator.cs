using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace ReadyM.Api.Generators;

[Generator]
internal class ClientRpcEventGenerator : IIncrementalGenerator
{
    private const string PlayerIdTypeName = "PlayerId";
    private const string SenderParameterName = "__sender";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var rpcMethods = context.SyntaxProvider
            .CreateSyntaxProvider(Predicate, Transform)
            .Where(m => m is not null)
            .Collect();

        context.RegisterSourceOutput(rpcMethods, GenerateSources);
    }

    private static bool Predicate(SyntaxNode node, CancellationToken _) =>
        node is MethodDeclarationSyntax method &&
        method.AttributeLists.Count > 0;

    private static RpcMethodInfo? Transform(GeneratorSyntaxContext context, CancellationToken _)
    {
        if (context.Node is not MethodDeclarationSyntax methodSyntax)
            return null;

        var methodSymbol = context.SemanticModel.GetDeclaredSymbol(methodSyntax) as IMethodSymbol;

        // Check for [RpcEvent] attribute via semantic model
        var rpcAttr = methodSymbol?.GetAttributes()
            .FirstOrDefault(attr => attr.AttributeClass?.Name is "RpcEventAttribute" or "RpcEvent");

        if (rpcAttr == null)
            return null;

        var attributeSyntax = rpcAttr
            .ApplicationSyntaxReference?.GetSyntax() as AttributeSyntax;
        var args = attributeSyntax!.ArgumentList!.Arguments;

        var constants = args.Select(arg => context.SemanticModel.GetOperation(arg.Expression)?.ConstantValue.Value)
            .Where(val => val is not null)
            .Select(x => x!.ToString())
            .ToArray();

        return new RpcMethodInfo(methodSymbol!, constants);
    }

    private static void GenerateSources(SourceProductionContext context, ImmutableArray<RpcMethodInfo?> rawMethods)
    {
        var methods = rawMethods
            .Where(m => m is not null)
            .Select(m => m!)
            .OrderBy(m => m.Symbol.ToDisplayString()) // Deterministic order
            .ToList();

        var groupsByClass = methods.GroupBy(m => m.Symbol.ContainingType, SymbolEqualityComparer.Default);

        foreach (var group in groupsByClass)
        {
            var eventIndex = 0;
            var maxEventCode = eventIndex;

            var classSymbol = group.Key;
            var ns = classSymbol!.ContainingNamespace.ToDisplayString();
            var className = classSymbol.Name;
            var fullClassName = classSymbol.ToDisplayString();

            var sb = new StringBuilder($$"""
                                         // <auto-generated/>
                                         using System;
                                         using LiteNetLib;
                                         using LiteNetLib.Utils;
                                         using ReadyM.Api.Multiplayer;
                                         using ReadyM.Api.Multiplayer.Protocol;
                                         using ReadyM.Api.Multiplayer.Protocol.Enums;
                                         using ReadyM.Api.Multiplayer.Client;
                                         using ReadyM.Api.Multiplayer.Extensions;

                                         namespace {{ns}};

                                         partial class {{className}}
                                         {

                                         """);

            var dispatchCases = new StringBuilder();

            foreach (var method in group)
            {
                if (eventIndex > ushort.MaxValue)
                {
                    sb.AppendLine($"""#error "Too many RPC events; limit is {ushort.MaxValue}." """);
                    break;
                }

                var methodSymbol = method.Symbol;
                var methodName = methodSymbol.Name;

                var parameters = methodSymbol.Parameters;

                var valid = true;
                int? senderIndex = null;
                int? eventCodeIndex = null;
                List<(ITypeSymbol? Type, bool IsSerializablePrimitive, bool IsNetSerializable)> paramTypes = [];

                for (var i = 0; i < parameters.Length; i++)
                {
                    var param = parameters[i];
                    if (param.Name == SenderParameterName)
                    {
                        if (param.Type.Name != PlayerIdTypeName)
                        {
                            valid = false;
                            break;
                        }

                        // PlayerId __sender
                        senderIndex = i;
                        paramTypes.Add((null, false, false));
                    }
                    else if (SerializationHelper.IsINetSerializable(param.Type))
                    {
                        // T payload
                        var isNetSerializable = true;
                        var payloadType = param.Type;
                        paramTypes.Add((payloadType, false, isNetSerializable));
                    }
                    else if (SerializationHelper.IsSerializablePrimitive(param.Type.SpecialType))
                    {
                        // int, string, etc.
                        var isSerializablePrimitive = true;
                        var payloadType = param.Type;
                        paramTypes.Add((payloadType, isSerializablePrimitive, false));
                    }
                    else
                    {
                        // T payload
                        var payloadType = param.Type; // T must be registered in RelayClient
                        paramTypes.Add((payloadType, false, false));
                    }
                }

                if (!valid)
                {
                    sb.AppendLine($"""#error "Invalid client RPC handler '{methodName}'. Supported signatures: void OnX([PlayerId __sender], [T arg...]) where T is either INetSerializable, or primitive" """);
                    continue;
                }

                var shortName = methodName.StartsWith("On") ? methodName.Substring(2) : methodName;

                var sendMethod = $"Send{shortName}";
                var sendParamList = new StringBuilder();

                var payloadCount = 0;
                for (var i = 0; i < paramTypes.Count; i++)
                {
                    if (i == senderIndex)
                        continue;

                    if (i == eventCodeIndex)
                        continue;

                    if (payloadCount > 0)
                        sendParamList.Append(", ");

                    var payloadType = paramTypes[i].Type;
                    sendParamList.Append(payloadType!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
                    sendParamList.Append($" payload{payloadCount}");
                    payloadCount++;
                }

                var relayMode = method.AttributeParams.FirstOrDefault(); // enum

                if (relayMode is null)
                {
                    sb.AppendLine($"""#warning "RelayMode must be specified in RpcEvent attribute for method '{methodName}'" """);
                    relayMode = "0"; // default
                }
                
                sb.AppendLine($$"""
                                    public void {{sendMethod}}({{sendParamList}})
                                    {
                                        // Read once: PlayerId is set on the network thread and cleared on
                                        // disconnect, so checking it and then using it can read two values.
                                        var senderPlayerId = RelayClient.PlayerId;
                                        if (!senderPlayerId.HasValue)
                                            return;
                                        
                                        var message = RelayMessage.ByRelayMode(Code({{eventIndex}}), senderPlayerId.Value, (RelayMode){{relayMode}}, DeliveryMethod.ReliableOrdered);
                                        var writer = message.Writer;
                                """);

                payloadCount = 0;
                for (var i = 0; i < paramTypes.Count; i++)
                {
                    var (_, isSerializablePrimitive, isNetSerializable) = paramTypes[i];

                    if (i == senderIndex)
                        continue;

                    if (i == eventCodeIndex)
                        continue;
                    
                    sb.AppendLine((isSerializablePrimitive, isNetSerializable) switch
                    {
                        (true, _) => $"        writer.Put(payload{payloadCount});",
                        (_, true) => $"        payload{payloadCount}.Serialize(writer);",
                        _         => $"        Serializer.SerializeObject(writer, payload{payloadCount});"
                    });
                    
                    payloadCount++;
                }


                sb.AppendLine("""
                                      RelayClient.SendMessage(message);
                                  }

                              """);

                dispatchCases.AppendLine($"            case {eventIndex}:\n            {{");

                payloadCount = 0;
                for (var i = 0; i < paramTypes.Count; i++)
                {
                    var (payloadType, isSerializablePrimitive, isNetSerializable) = paramTypes[i];

                    if (i == senderIndex || i == eventCodeIndex)
                        continue;
                    
                    switch (isSerializablePrimitive, isNetSerializable)
                    {
                        case (true, _):
                            var getMethod = SerializationHelper.GetDeserializationMethod(payloadType!.SpecialType);
                            dispatchCases.AppendLine($"                var payload{payloadCount} = reader.{getMethod}();");
                            break;
                        case (_, true):
                            dispatchCases.AppendLine($"                var payload{payloadCount} = new {payloadType}();");
                            dispatchCases.AppendLine($"                payload{payloadCount}.Deserialize(reader);");
                            break;
                        default:
                            dispatchCases.AppendLine($"                var payload{payloadCount} = Serializer.DeserializeObject<{payloadType!.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}>(reader);");
                            break;
                    }

                    payloadCount++;
                }

                dispatchCases.Append("                RunOnGameThread(() => { ");
                dispatchCases.Append(methodName);
                dispatchCases.Append('(');

                payloadCount = 0;
                for (var i = 0; i < paramTypes.Count; i++)
                {
                    if (i > 0)
                        dispatchCases.Append(", ");

                    if (i == senderIndex)
                    {
                        dispatchCases.Append("header.Sender");
                        continue;
                    }

                    if (i == eventCodeIndex)
                    {
                        dispatchCases.Append("header.EventCode");
                        continue;
                    }

                    dispatchCases.Append($"payload{payloadCount}");
                    payloadCount++;
                }

                dispatchCases.AppendLine("); });");
                dispatchCases.AppendLine("                break;");
                dispatchCases.AppendLine("            }");

                maxEventCode = eventIndex;
                eventIndex++;
            }

            // Emit OnCustomEvent override
            sb.AppendLine($$"""
                                private void OnCustomRpcMessageHandler(CustomRelayEventHeader header, NetDataReader reader)
                                {
                                    switch ((int)header.EventCode - (int)Code(0))
                                    {
                            {{dispatchCases}}
                                        default:
                                            break;
                                    }
                                }
                                    
                                protected override void InitRpc()
                                {
                                    RelayClient.AddClientRpcMessageHandler(Code(0), Code({{maxEventCode}}), OnCustomRpcMessageHandler);
                                }
                                    
                                protected override void DeInitRpc()
                                {
                                    RelayClient.RemoveClientRpcMessageHandler(Code(0), Code({{maxEventCode}}), OnCustomRpcMessageHandler);
                                }
                                
                                protected override ushort EventsCount => {{maxEventCode + 1}};

                                private RelayMessageCode Code(int eventIndex)
                                    => (RelayMessageCode)((int)RelayMessageCode.MinAnyCustomEvent + Offset + eventIndex);
                            """);

            sb.AppendLine("}");

            var hintName = $"{fullClassName.Replace('.', '_')}_RpcEvents.g.cs";
            context.AddSource(hintName, sb.ToString());
        }
    }

    private sealed class RpcMethodInfo(IMethodSymbol symbol, string[] attr)
    {
        public IMethodSymbol Symbol { get; } = symbol;
        public string[] AttributeParams { get; } = attr;
    }
}